                            Text(
                                text = "Default Target Recipient",
                                fontSize = 14.sp,
                                fontWeight = FontWeight.Bold,
                                color = TextPrimary
                            )
                            Text(
                                text = "Pre-selected in new excuse setup",
                                fontSize = 11.sp,
                                color = TextMuted
                            )
