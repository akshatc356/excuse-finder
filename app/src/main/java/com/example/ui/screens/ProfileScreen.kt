                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(18.dp))
                    .background(CardBg)
                    .border(1.dp, CardBorder, RoundedCornerShape(18.dp))
                    .clickable { showResetStatsConfirm = true }
                    .padding(16.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column {
                        Text(
                            text = "Reset Operator Statistics",
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Bold,
                            color = TextPrimary
                        )
                        Text(
                            text = "Restart counter totals without deleting your excuses",
                            fontSize = 12.sp,
                            color = TextSecondary
                        )
                    }

                    SecurityStampBadge("RESET", AccentYellow)
                }
            }

            Spacer(modifier = Modifier.height(12.dp))

