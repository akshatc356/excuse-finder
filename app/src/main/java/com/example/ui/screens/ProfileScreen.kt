                                text = if (customApiKey.isNotBlank()) "Custom Key Active • $customModel" else "Active • $customModel",
                                fontFamily = FontFamily.Monospace,
                                fontSize = 11.sp,
                                color = AccentYellow
                            )
                        }
                    }

                    SecurityStampBadge("CONFIG", AccentYellow)
                }
            }

            Spacer(modifier = Modifier.height(20.dp))

            // System Settings
            Text(
                text = "TERMINAL SETTINGS",
                fontFamily = FontFamily.Monospace,
                fontSize = 11.sp,
                fontWeight = FontWeight.Bold,
                letterSpacing = 1.sp,
                color = TextSecondary
            )

            Spacer(modifier = Modifier.height(10.dp))

            // Haptics Switch Row
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(18.dp))
                    .background(CardBg)
                    .border(1.dp, CardBorder, RoundedCornerShape(18.dp))
                    .padding(horizontal = 16.dp, vertical = 12.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text(
                            text = "Haptic Tactile Feedback",
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Bold,
                            color = TextPrimary
                        )
                        Text(
                            text = "Tactile vibration when copying alibis and selecting options",
                            fontSize = 12.sp,
                            color = TextSecondary
                        )
                    }

                    Switch(
                        checked = hapticsEnabled,
                        onCheckedChange = { viewModel.toggleHaptics(it) },
                        colors = SwitchDefaults.colors(
                            checkedThumbColor = Color(0xFF000000),
                            checkedTrackColor = AccentYellow,
                            uncheckedThumbColor = TextMuted,
                            uncheckedTrackColor = CardBgElevated
                        )
                    )
                }
            }

