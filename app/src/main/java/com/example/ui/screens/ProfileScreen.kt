        if (showEditNameDialog) {
            AlertDialog(
                onDismissRequest = { showEditNameDialog = false },
                containerColor = CardBg,
                shape = RoundedCornerShape(20.dp),
                title = {
                    Text(
                        text = "CHANGE OPERATOR NAME",
                        fontFamily = FontFamily.Monospace,
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Black,
                        color = AccentYellow
                    )
                },
                text = {
                    Column {
                        Text(
                            text = "Set your personal alias or handle for this terminal.",
                            fontSize = 13.sp,
                            color = TextSecondary
                        )
                        Spacer(modifier = Modifier.height(12.dp))
                        OutlinedTextField(
                            value = editNameInput,
                            onValueChange = { editNameInput = it },
                            singleLine = true,
                            colors = OutlinedTextFieldDefaults.colors(
                                focusedBorderColor = AccentYellow,
                                unfocusedBorderColor = CardBorder,
                                focusedTextColor = TextPrimary,
                                unfocusedTextColor = TextPrimary,
                                focusedContainerColor = CardBgElevated,
                                unfocusedContainerColor = CardBgElevated,
                                cursorColor = AccentYellow
                            )
                        )
                    }
                },
                confirmButton = {
                    TextButton(
                        onClick = {
                            viewModel.setUserName(editNameInput)
                            showEditNameDialog = false
                        }
                    ) {
                        Text("SAVE", fontWeight = FontWeight.Bold, color = AccentYellow)
                    }
                },
                dismissButton = {
                    TextButton(onClick = { showEditNameDialog = false }) {
                        Text("CANCEL", color = TextSecondary)
                    }
                }
            )
        }

        // Edit Bio Dialog
        if (showEditBioDialog) {
            AlertDialog(
                onDismissRequest = { showEditBioDialog = false },
                containerColor = CardBg,
                shape = RoundedCornerShape(20.dp),
                title = {
                    Text(
                        text = "EDIT ALIBI STRATEGY",
                        fontFamily = FontFamily.Monospace,
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Black,
                        color = AccentYellow
                    )
                },
                text = {
                    Column {
                        Text(
                            text = "Describe your usual excuse approach or personal bio note.",
                            fontSize = 13.sp,
                            color = TextSecondary
                        )
                        Spacer(modifier = Modifier.height(12.dp))
                        OutlinedTextField(
                            value = editBioInput,
                            onValueChange = { editBioInput = it },
                            colors = OutlinedTextFieldDefaults.colors(
                                focusedBorderColor = AccentYellow,
                                unfocusedBorderColor = CardBorder,
                                focusedTextColor = TextPrimary,
                                unfocusedTextColor = TextPrimary,
                                focusedContainerColor = CardBgElevated,
                                unfocusedContainerColor = CardBgElevated,
                                cursorColor = AccentYellow
                            )
                        )
                    }
                },
                confirmButton = {
                    TextButton(
                        onClick = {
                            viewModel.setUserBio(editBioInput)
                            showEditBioDialog = false
                        }
                    ) {
