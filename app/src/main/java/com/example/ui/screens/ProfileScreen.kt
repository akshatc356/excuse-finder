            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(18.dp))
                    .background(CardBg)
                    .border(1.dp, CardBorder, RoundedCornerShape(18.dp))
                    .clickable { showClearConfirm = true }
                    .padding(16.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column {
                        Text(
                            text = "Clear Incident Archive",
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Bold,
                            color = WarningRed
                        )
                        Text(
                            text = "Erase all saved alibi history records from SQLite database",
                            fontSize = 12.sp,
                            color = TextSecondary
                        )
                    }

                    SecurityStampBadge("WIPE", WarningRed)
                }
            }
        }

