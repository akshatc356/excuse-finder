                        Column {
                            Text(
                                text = "Default Excuse Vibe / Tone",
                                fontSize = 14.sp,
                                fontWeight = FontWeight.Bold,
                                color = TextPrimary
                            )
                            Text(
                                text = "Your preferred communication baseline",
                                fontSize = 11.sp,
                                color = TextMuted
